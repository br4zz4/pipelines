import os
import re
import sys

import yaml

HEADER = "# generated by br4zz4/pipelines render — do not edit"
RUNNER = "blacksmith-2vcpu-ubuntu-2404"
TAG_PATTERN = "'*.[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9].*'"


def read(directory, name):
    with open(os.path.join(directory, name), encoding="utf-8") as handle:
        return handle.read()


def jobs(text):
    lines = text.split("\n")
    result = []
    current = None
    in_jobs = False
    for line in lines:
        if re.match(r"^jobs:\s*$", line):
            in_jobs = True
            continue
        if in_jobs and re.match(r"^\S", line):
            in_jobs = False
        if not in_jobs:
            continue
        match = re.match(r"^  ([A-Za-z0-9_-]+):\s*$", line)
        if match:
            current = (match.group(1), [])
            result.append(current)
        elif current is not None:
            current[1].append(line)
    return result


def scalar(block, key):
    for line in block:
        match = re.match(r"^    " + re.escape(key) + r":\s*(.*?)\s*$", line)
        if match:
            return match.group(1)
    return None


def with_value(block, key):
    for line in block:
        match = re.match(r"^      " + re.escape(key) + r":\s*(.*?)\s*$", line)
        if match:
            return match.group(1).strip("'\"")
    return None


def needs(block):
    inline = scalar(block, "needs")
    if inline:
        return set(re.findall(r"[A-Za-z0-9_-]+", inline.strip("[]")))
    found = set()
    capture = False
    for line in block:
        if re.match(r"^    needs:\s*$", line):
            capture = True
            continue
        if capture:
            match = re.match(r"^      - ([A-Za-z0-9_-]+)\s*$", line)
            if match:
                found.add(match.group(1))
            else:
                break
    return found


def steps(block):
    items = []
    for line in block:
        if re.match(r"^      - ", line):
            items.append([line])
        elif items and re.match(r"^        \S", line):
            items[-1].append(line)
    return items


def check(directory, ns, modules):
    failures = []

    def fail(message):
        failures.append(message)

    names = sorted(modules)
    upper = ns.upper()
    texts = {name: read(directory, name) for name in ("pr.yml", "main.yml", "build.yml", "deploy.yml")}

    for name, text in texts.items():
        if text.split("\n")[0] != HEADER:
            fail(f"{name}: first line is not the generated header")
        if "matrix" in text:
            fail(f"{name}: contains matrix")
        if re.search(r"^    environment:", text, re.M):
            fail(f"{name}: contains environment:")
        for line in text.split("\n"):
            if re.match(r"^\s*(- )?name:", line) and "${{" in line:
                fail(f"{name}: name line with expression: {line.strip()}")
        for job_id, block in jobs(text):
            for item in steps(block):
                if not any(re.match(r"^(      - |        )name:", line) for line in item):
                    fail(f"{name}: step without name in job {job_id}: {item[0].strip()}")
        if f"WARD_KEY_{upper}" not in text:
            fail(f"{name}: missing WARD_KEY_{upper}")
        if "_RESTRICTED" in text:
            fail(f"{name}: contains _RESTRICTED (the default comes from the reusable workflow)")

    docs = {name: yaml.safe_load(text) for name, text in texts.items()}

    def job_map(name):
        return docs[name]["jobs"]

    def need_set(job):
        value = job.get("needs") or []
        return {value} if isinstance(value, str) else set(value)

    def step_names(job):
        return [step.get("name") for step in job.get("steps", [])]

    expected_ids = {
        "pr.yml": ["conform", "detect"] + [f"{m}-{part}" for m in names for part in ("changes", "code", "infra")] + ["gate"],
        "main.yml": ["conform", "detect", "split"],
        "build.yml": ["conform", "target", "build"],
        "deploy.yml": ["conform", "release-start", "deploy"],
    }
    for name in expected_ids:
        ids = list(job_map(name).keys())
        if ids != expected_ids[name]:
            fail(f"{name}: jobs {ids} != {expected_ids[name]}")
        for job_id in ids:
            if job_id in modules and name != "deploy.yml":
                fail(f"{name}: job named after module {job_id}")

    for name in ("pr.yml",):
        for job_id, job in job_map(name).items():
            for lane, workflow in (("code", "code.yml"), ("infra", "infra.yml")):
                if not job_id.endswith(f"-{lane}"):
                    continue
                module = job_id[: -len(lane) - 1]
                if job.get("name") != f"{module} / {lane}":
                    fail(f"{name}: job {job_id} name is {job.get('name')}")
                if job.get("uses") != f"br4zz4/pipelines/.github/workflows/{workflow}@v2":
                    fail(f"{name}: job {job_id} uses {job.get('uses')}")
                if name == "pr.yml":
                    expected_if = f"${{{{ needs.{module}-changes.outputs.{lane} == 'true' }}}}"
                else:
                    expected_if = f"${{{{ needs.{module}-reuse.outputs.{lane} == 'true' }}}}"
                if job.get("if") != expected_if:
                    fail(f"{name}: job {job_id} if {job.get('if')!r}")
                raw_needs = job.get("needs")
                source = f"{module}-changes" if name == "pr.yml" else f"{module}-reuse"
                if lane == "code" and raw_needs != source:
                    fail(f"{name}: job {job_id} needs {raw_needs!r} != {source!r}")
                if lane == "infra" and raw_needs != [source, "detect"]:
                    fail(f"{name}: job {job_id} needs {raw_needs!r} != {[source, 'detect']!r}")
                with_ = job.get("with") or {}
                if with_.get("module") != module:
                    fail(f"{name}: job {job_id} module {with_.get('module')}")
                if "vault" not in with_:
                    fail(f"{name}: job {job_id} without vault")
                if lane == "code":
                    if "code_dir" not in with_:
                        fail(f"{name}: job {job_id} without code_dir")
                    got = str(with_.get("services", "")).replace(" ", "")
                    if got != ",".join(modules[module]):
                        fail(f"{name}: job {job_id} services {got!r} != {','.join(modules[module])!r}")
                elif "infra_dir" not in with_:
                    fail(f"{name}: job {job_id} without infra_dir")
                if "WARD_KEY" not in (job.get("secrets") or {}):
                    fail(f"{name}: job {job_id} without WARD_KEY secret")
                skips = ("lint", "audit", "test") if lane == "code" else ("validate", "plan")
                for skip in skips:
                    want = f"${{{{ needs.{module}-reuse.outputs.{skip} }}}}"
                    got = with_.get(f"skip_{skip}")
                    if name == "main.yml" and got != want:
                        fail(f"{name}: job {job_id} skip_{skip} {got!r}")
                    if name == "pr.yml" and got is not None:
                        fail(f"{name}: job {job_id} has skip_{skip}")

    for module in names:
        pr_jobs = job_map("pr.yml")
        changes = pr_jobs.get(f"{module}-changes")
        if changes is None:
            fail(f"pr.yml: job {module}-changes missing")
        else:
            if changes.get("name") != f"{module} / changes":
                fail(f"pr.yml: {module}-changes name {changes.get('name')!r}")
            if changes.get("needs") != ["conform", "detect"]:
                fail(f"pr.yml: {module}-changes needs {changes.get('needs')!r} != ['conform', 'detect']")
            want_changes_if = f"${{{{ fromJSON(needs.detect.outputs.changes).{module}.any }}}}"
            if changes.get("if") != want_changes_if:
                fail(f"pr.yml: {module}-changes if {changes.get('if')!r}")
            if "uses" in changes:
                fail(f"pr.yml: {module}-changes has uses")
            if set(changes.get("outputs") or {}) != {"code", "infra"}:
                fail(f"pr.yml: {module}-changes outputs {sorted(changes.get('outputs') or {})}")
            for side in ("code", "infra"):
                want_out = f"${{{{ fromJSON(needs.detect.outputs.changes).{module}.{side} }}}}"
                got_out = (changes.get("outputs") or {}).get(side)
                if got_out != want_out:
                    fail(f"pr.yml: {module}-changes output {side} {got_out!r}")

    for name in ("pr.yml", "main.yml"):
        if need_set(job_map(name)["detect"]):
            fail(f"{name}: detect has needs {sorted(need_set(job_map(name)['detect']))}")
    if need_set(job_map("deploy.yml")["release-start"]):
        fail(f"deploy.yml: release-start has needs {sorted(need_set(job_map('deploy.yml')['release-start']))}")
    deploy_job = job_map("deploy.yml")["deploy"]
    if need_set(deploy_job) != {"conform", "release-start"}:
        fail(f"deploy.yml: job deploy needs {sorted(need_set(deploy_job))} != ['conform', 'release-start']")
    if "services" in (deploy_job.get("with") or {}):
        fail("deploy.yml: job deploy passes services")
    for job_id, job in job_map("deploy.yml").items():
        if job_id in modules:
            if job.get("name") != job_id:
                fail(f"deploy.yml: job {job_id} name is {job.get('name')}")
            if job.get("uses") != "br4zz4/pipelines/.github/workflows/deploy.yml@v2":
                fail(f"deploy.yml: job {job_id} uses {job.get('uses')}")
    for name in ("main.yml", "deploy.yml"):
        if "gate" in job_map(name):
            fail(f"{name}: has gate job")

    pr = texts["pr.yml"]
    if not re.search(r"^on:\s*\n(\s+.*\n)*?\s+pull_request:?", pr, re.M):
        fail("pr.yml: not on pull_request")
    if not re.search(r"^concurrency:\s*\n(\s+.*\n)*?\s+cancel-in-progress:\s*true", pr, re.M):
        fail("pr.yml: concurrency without cancel-in-progress true")

    if not re.search(r"branches:\s*\[\s*main\s*\]", texts["main.yml"]):
        fail("main.yml: push branches [ main ] missing")
    if "concurrency" in texts["main.yml"]:
        fail("main.yml: has concurrency")
    main_jobs = job_map("main.yml")
    split = main_jobs["split"]
    if split.get("needs") != ["conform", "detect"]:
        fail(f"main.yml: split needs {split.get('needs')!r}")
    if split.get("name") != "build / split":
        fail(f"main.yml: split name {split.get('name')!r}")
    split_steps = split.get("steps", [])
    if step_names(split) != ["checkout", "secrets", "split"]:
        fail(f"main.yml: split steps {step_names(split)}")
    else:
        checkout_with = split_steps[0].get("with") or {}
        if checkout_with.get("fetch-depth") != 0 or checkout_with.get("fetch-tags") is not True:
            fail(f"main.yml: split checkout {checkout_with!r}")
        secrets_with = split_steps[1].get("with") or {}
        if secrets_with.get("scopes") != f"{ns}:secrets.ci.common":
            fail(f"main.yml: split secrets scopes {secrets_with.get('scopes')!r}")
        if split_steps[2].get("uses") != "br4zz4/pipelines/actions/split@v2":
            fail(f"main.yml: split uses {split_steps[2].get('uses')!r}")
        split_with = split_steps[2].get("with") or {}
        if split_with.get("changes") != "${{ needs.detect.outputs.changes }}":
            fail(f"main.yml: split changes {split_with.get('changes')!r}")
        if split_with.get("token") != "${{ env.GH_PIPELINES_TOKEN }}":
            fail(f"main.yml: split token {split_with.get('token')!r}")

    build_doc = docs["build.yml"]
    build_text = texts["build.yml"]
    triggers = build_doc.get("on") if "on" in build_doc else build_doc.get(True)
    if (triggers.get("push") or {}).get("tags") != ["build/**"]:
        fail(f"build.yml: tags {triggers!r}")
    if build_doc.get("run-name") != "${{ github.ref_name }}":
        fail(f"build.yml: run-name {build_doc.get('run-name')!r}")
    perms = build_doc.get("permissions") or {}
    if perms.get("checks") != "read" or perms.get("pull-requests") != "read":
        fail(f"build.yml: permissions {perms!r}")
    build_jobs = job_map("build.yml")
    if need_set(build_jobs["target"]):
        fail("build.yml: target has needs")
    target_outputs = build_jobs["target"].get("outputs") or {}
    if target_outputs.get("reuse") != "${{ steps.target.outputs.reuse }}":
        fail(f"build.yml: target reuse output {target_outputs.get('reuse')!r}")
    build_job = build_jobs["build"]
    if build_job.get("needs") != ["conform", "target"]:
        fail(f"build.yml: build needs {build_job.get('needs')!r}")
    concurrency = build_job.get("concurrency") or {}
    if concurrency.get("group") != "build-${{ needs.target.outputs.module }}" or concurrency.get("cancel-in-progress") is not True:
        fail(f"build.yml: build concurrency {concurrency!r}")
    if build_job.get("uses") != "br4zz4/pipelines/.github/workflows/build.yml@v2":
        fail(f"build.yml: build uses {build_job.get('uses')!r}")
    build_with = build_job.get("with") or {}
    for key in ("module", "tag", "code_dir", "infra_dir", "services", "code", "infra", "reuse"):
        if build_with.get(key) != f"${{{{ needs.target.outputs.{key} }}}}":
            fail(f"build.yml: build with {key} {build_with.get(key)!r}")
    if "vault" not in build_with:
        fail("build.yml: build without vault")
    if "WARD_KEY" not in (build_job.get("secrets") or {}):
        fail("build.yml: build without WARD_KEY secret")
    for module in names:
        if module in build_text and module not in ("conform",):
            fail(f"build.yml: embeds module name {module}")

    deploy = texts["deploy.yml"]
    if "workflow_dispatch" not in deploy:
        fail("deploy.yml: missing workflow_dispatch")
    if TAG_PATTERN not in deploy:
        fail("deploy.yml: missing tag pattern")
    if not re.search(r"^run-name:", deploy, re.M):
        fail("deploy.yml: missing run-name")
    deploy_doc = docs["deploy.yml"]
    dispatch = ((deploy_doc.get("on") if "on" in deploy_doc else deploy_doc.get(True)).get("workflow_dispatch") or {}).get("inputs") or {}
    rollback_input = dispatch.get("rollback_to") or {}
    if rollback_input.get("type") != "string" or rollback_input.get("default") != "":
        fail(f"deploy.yml: rollback_to input {rollback_input!r}")
    if (deploy_doc.get("permissions") or {}).get("actions") != "write":
        fail("deploy.yml: permissions without actions: write")
    if not re.search(r"rollback · .* \(from ", deploy_doc.get("run-name", "")):
        fail("deploy.yml: run-name without the rollback format")
    start = job_map("deploy.yml")["release-start"]
    if not {"code_dir", "infra_dir", "rollback_of"} <= set(start.get("outputs") or {}):
        fail(f"deploy.yml: release-start outputs {sorted(start.get('outputs') or {})}")
    releases_step = [s for s in start.get("steps", []) if s.get("id") == "releases"]
    if not releases_step or (releases_step[0].get("with") or {}).get("rollback_to") != "${{ inputs.rollback_to }}":
        fail("deploy.yml: releases step without rollback_to input")
    for key in ("code_dir", "infra_dir", "rollback_of"):
        if (deploy_job.get("with") or {}).get(key) != f"${{{{ needs.release-start.outputs.{key} }}}}":
            fail(f"deploy.yml: deploy with {key} {(deploy_job.get('with') or {}).get(key)!r}")
    if "services/events" in deploy or "modules/" in deploy:
        fail("deploy.yml: embeds a directory")

    gate = [block for job_id, block in jobs(pr) if job_id == "gate"]
    parsed_pr = jobs(pr)
    if not gate:
        fail("pr.yml: missing gate job")
    else:
        block = gate[0]
        if parsed_pr[-1][0] != "gate":
            fail("pr.yml: gate is not the last job")
        if scalar(block, "name") != "check/pr":
            fail(f"pr.yml: gate name {scalar(block, 'name')}")
        if scalar(block, "if") != "${{ always() }}":
            fail(f"pr.yml: gate if {scalar(block, 'if')}")
        lanes = {f"{m}-{part}" for m in names for part in ("changes", "code", "infra")}
        if needs(block) != {"conform", "detect"} | lanes:
            fail(f"pr.yml: gate needs {sorted(needs(block))}")
        if scalar(block, "uses") is not None:
            fail("pr.yml: gate has uses")
        if scalar(block, "runs-on") != RUNNER:
            fail(f"pr.yml: gate runs-on {scalar(block, 'runs-on')}")
        joined = "\n".join(block)
        if not re.search(r"^      - name: gate\s*$", joined, re.M):
            fail("pr.yml: gate step name")
        if "uses: br4zz4/pipelines/actions/gate@v2" not in joined:
            fail("pr.yml: gate action")
        if "results: ${{ toJSON(needs) }}" not in joined:
            fail("pr.yml: gate results")

    return failures


def main():
    directory, ns = sys.argv[1], sys.argv[2]
    modules = {}
    for spec in sys.argv[3:]:
        name, _, services = spec.partition(":")
        modules[name] = [s for s in services.split(",") if s]
    failures = check(directory, ns, modules)
    for failure in failures:
        print(failure)
    sys.exit(1 if failures else 0)


main()
