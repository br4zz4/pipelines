import re
import sys

import yaml

HEADER = "# generated by br4zz4/pipelines render — do not edit"


def main():
    path, ref, postgres = sys.argv[1], sys.argv[2], sys.argv[3] == "postgres"
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    failures = []

    def fail(message):
        failures.append(message)

    if text.split("\n")[0] != HEADER:
        fail("first line is not the generated header")
    for forbidden in ("allowed_non_write_users", "allowed_bots"):
        if forbidden in text:
            fail(f"contains {forbidden}")

    doc = yaml.safe_load(text)
    if doc.get("name") != "fix":
        fail(f"name {doc.get('name')!r}")
    triggers = doc.get("on") if "on" in doc else doc.get(True)
    triggers = triggers or {}
    expected = {
        "issue_comment": "created",
        "pull_request_review_comment": "created",
        "pull_request_review": "submitted",
        "issues": "labeled",
    }
    for event, kind in expected.items():
        types = (triggers.get(event) or {}).get("types")
        if types != [kind]:
            fail(f"on.{event}.types {types!r}")

    perms = doc.get("permissions") or {}
    for key, value in {
        "contents": "write",
        "pull-requests": "write",
        "issues": "write",
        "actions": "read",
        "id-token": "write",
    }.items():
        if perms.get(key) != value:
            fail(f"permissions.{key} {perms.get(key)!r}")

    jobs = doc.get("jobs") or {}
    job = jobs.get("fix")
    if job is None:
        fail("job fix missing")
        job = {}
    condition = str(job.get("if", ""))
    if "fix:requested" not in condition or "@claude" not in condition:
        fail(f"job fix if {condition!r}")

    for marker in ("[autofix]", "[fix]"):
        if f"!startsWith(github.event.comment.body || github.event.review.body, '{marker}')" not in condition:
            fail(f"job fix if does not exclude {marker}")

    if "concurrency" in doc:
        fail("concurrency at the workflow level")
    job_concurrency = job.get("concurrency") or {}
    group = str(job_concurrency.get("group", ""))
    if not group.startswith("fix-"):
        fail(f"job concurrency group {group!r}")
    if group != "fix-${{ github.event.issue.number || github.event.pull_request.number }}":
        fail(f"job concurrency group {group!r}")
    if job_concurrency.get("cancel-in-progress") is not False:
        fail(f"job concurrency cancel-in-progress {job_concurrency.get('cancel-in-progress')!r}")

    services = job.get("services") or {}
    if postgres and "postgres" not in services:
        fail("job fix lacks services.postgres")
    if not postgres and "postgres" in services:
        fail("job fix has services.postgres without a postgres module")

    steps = job.get("steps") or []
    checkouts = [s for s in steps if str(s.get("uses", "")).startswith("actions/checkout@")]
    if not checkouts:
        fail("job fix has no checkout step")
    else:
        checkout_with = checkouts[0].get("with") or {}
        if checkout_with.get("fetch-depth") != 0:
            fail(f"checkout fetch-depth {checkout_with.get('fetch-depth')!r}")
        if checkout_with.get("persist-credentials") is False or str(checkout_with.get("persist-credentials")).lower() == "false":
            fail("checkout sets persist-credentials: false")
    select = [s for s in steps if str(s.get("uses", "")).startswith("br4zz4/pipelines/actions/fix-run@")]
    if not select:
        fail("no step uses br4zz4/pipelines/actions/fix-run")
    else:
        uses = select[0]["uses"]
        if uses != f"br4zz4/pipelines/actions/fix-run@{ref}":
            fail(f"fix-run uses {uses!r}")
    agents = [s for s in steps if s.get("id") == "agent"]
    if not agents:
        fail("no step with id agent")
    else:
        agent = agents[0]
        if agent.get("uses") != "anthropics/claude-code-action@v1":
            fail(f"agent uses {agent.get('uses')!r}")
        with_ = agent.get("with") or {}
        if with_.get("trigger_phrase") != "@claude":
            fail(f"trigger_phrase {with_.get('trigger_phrase')!r}")
        if with_.get("label_trigger") != "fix:requested":
            fail(f"label_trigger {with_.get('label_trigger')!r}")
        if with_.get("branch_prefix") != "agent/":
            fail(f"branch_prefix {with_.get('branch_prefix')!r}")
        args = str(with_.get("claude_args", ""))
        for needle in (".github/workflows/**", ".ward/**", "gh pr merge", "--model opus"):
            if needle not in args:
                fail(f"claude_args lacks {needle!r}")
        for needle in (
            "Bash(git status:*)",
            "Bash(git diff:*)",
            "Bash(git log:*)",
            "Bash(git show:*)",
            "Bash(git fetch:*)",
            "Bash(gh pr create --draft:*)",
        ):
            if needle not in args:
                fail(f"claude_args lacks {needle!r}")
        for loose in (
            "Bash(git:*)",
            "Bash(gh pr create:*)",
            "Bash(git add:*)",
            "Bash(git commit:*)",
            "Bash(git push origin agent/*)",
            "Bash(git switch:*)",
            "Bash(git push",
        ):
            if loose in args:
                fail(f"claude_args allows {loose!r}")
        if "outcome" not in str(agent.get("if", "")):
            fail(f"agent if {agent.get('if')!r}")

    for failure in failures:
        print(failure)
    sys.exit(1 if failures else 0)


main()
