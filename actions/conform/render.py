def generated_files(project):
    extra = ()
    if project["promote"] is not None:
        extra += (PROMOTE_FILE,)
    if project["autofix"] is not None:
        extra += (AUTOFIX_FILE,)
        if project["autofix"]["sentry"] is not None:
            extra += (INTAKE_FILE,)
    return FILES + extra


def render(project, ref=DEFAULT_REF):
    builders = {
        "pr.yml": render_pr,
        "main.yml": render_main,
        "build.yml": render_build,
        "deploy.yml": render_deploy,
        PROMOTE_FILE: render_promote,
        AUTOFIX_FILE: render_autofix,
        INTAKE_FILE: render_intake,
    }
    return {name: "\n".join(builders[name](project, ref)) + "\n" for name in generated_files(project)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", required=True)
    parser.add_argument("--out")
    parser.add_argument("--ref", default=DEFAULT_REF, help="ref of br4zz4/pipelines the workflows call")
    args = parser.parse_args(argv)
    try:
        files = render(load_project(args.root), args.ref)
    except RenderError as error:
        print(f"render: {error}", file=sys.stderr)
        return 2
    out = args.out or os.path.join(args.root, ".github", "workflows")
    os.makedirs(out, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(out, name), "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
