#!/usr/bin/env python3
"""render — write a project's pr, main and deploy workflows from its registry.

Reads <root>/.github/modules.json and <root>/.ward/config.yaml, and writes
pr.yml, main.yml and deploy.yml. The output is deterministic: modules are
sorted and nothing depends on the clock or the environment.

Usage: render.py --root <project> [--out <dir>] [--ref <ref>]
"""

import argparse
import json
import os
import re
import sys

HEADER = "# generated by br4zz4/pipelines render — do not edit"
RUNNER = "blacksmith-2vcpu-ubuntu-2404"
RUNNER_BUILD = "blacksmith-4vcpu-ubuntu-2404"
CHECKS = ("lint", "audit", "test", "validate", "plan")
PIPELINES = "br4zz4/pipelines"
DEFAULT_REF = "v1"
MODULE_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
SERVICES = ("postgres", "redis")
FILES = ("pr.yml", "main.yml", "deploy.yml")
TAG_GLOB = "'*.[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9].*'"


class RenderError(ValueError):
    pass


def read_json(path):
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except FileNotFoundError:
        raise RenderError(f"missing {path}")
    except json.JSONDecodeError as error:
        raise RenderError(f"{path}: invalid JSON ({error})")


def ward_vaults(path):
    try:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    except FileNotFoundError:
        raise RenderError(f"missing {path}")
    names, in_vaults = [], False
    for line in text.splitlines():
        if re.match(r"^vaults:\s*$", line):
            in_vaults = True
            continue
        if in_vaults and line.strip() and not line[0].isspace() and not line.startswith("-"):
            in_vaults = False
        if not in_vaults:
            continue
        match = re.match(r"^\s*-?\s*name:\s*['\"]?([^'\"\s#]+)", line)
        if match:
            names.append(match.group(1))
    return names


def namespace(vaults):
    """Return (namespace, has_restricted). The project namespace is the default
    vault that has a `::restricted` pair; without any pair, the only default."""
    defaults = {}
    for name in vaults:
        if name.endswith("::restricted"):
            continue
        base = name[: -len("::default")] if name.endswith("::default") else name
        if "::" in base:
            continue
        if base in defaults:
            raise RenderError(f".ward/config.yaml declares vault '{base}' twice (default and ::default)")
        defaults[base] = name
    paired = sorted(ns for ns in defaults if f"{ns}::restricted" in vaults)
    if len(paired) > 1:
        raise RenderError(f".ward/config.yaml declares more than one project namespace: {', '.join(paired)}")
    if paired:
        return paired[0], True
    if len(defaults) == 1:
        return next(iter(defaults)), False
    if not defaults:
        raise RenderError(".ward/config.yaml must declare a default vault <ns> (or <ns>::default)")
    raise RenderError(
        ".ward/config.yaml declares several default vaults without a ::restricted pair to pick the project: "
        + ", ".join(sorted(defaults))
    )


def key_name(ns, restricted=False):
    base = "WARD_KEY_" + re.sub(r"[^A-Za-z0-9]", "_", ns).upper()
    return base + "_RESTRICTED" if restricted else base


def load_project(root):
    registry = read_json(os.path.join(root, ".github", "modules.json"))
    ns, restricted = namespace(ward_vaults(os.path.join(root, ".ward", "config.yaml")))
    modules = registry.get("modules") or {}
    if not modules:
        raise RenderError(".github/modules.json declares no modules")
    result = []
    for name in sorted(modules):
        if not MODULE_NAME.match(name):
            raise RenderError(f"module '{name}' must match [a-z][a-z0-9_]*")
        spec = modules[name] or {}
        services = list(spec.get("services") or [])
        for service in services:
            if service not in SERVICES:
                raise RenderError(f"module '{name}': service '{service}' is not in the catalog ({', '.join(SERVICES)})")
        code = (spec.get("code") or {}).get("dir") or f"modules/{name}/code"
        infra = (spec.get("infra") or {}).get("dir") or f"modules/{name}/infra"
        result.append({"name": name, "services": services, "code": code, "infra": infra})
    return {
        "ns": ns,
        "restricted": restricted,
        "modules": result,
        "extra": list(registry.get("extra_workflows") or []),
        "shared": list(registry.get("shared") or []),
    }


def checkout(extra=None):
    lines = ["      - name: checkout", "        uses: actions/checkout@v6"]
    if extra:
        lines.append("        with:")
        lines.extend(f"          {line}" for line in extra)
    return lines


def conform_job(project, mode, ref):
    ns = project["ns"]
    lines = ["  conform:", "    name: conform", f"    runs-on: {RUNNER}", "    timeout-minutes: 5", "    steps:"]
    if mode == "fix":
        lines += checkout(
            [
                "ref: ${{ github.head_ref }}",
                "repository: ${{ github.event.pull_request.head.repo.full_name }}",
                "persist-credentials: false",
            ]
        )
        lines += [
            "      - name: conform",
            f"        uses: {PIPELINES}/actions/conform@{ref}",
            "        with:",
            "          mode: fix",
            f"          vault: {ns}",
            f"          key: ${{{{ github.event.pull_request.head.repo.full_name == github.repository && secrets.{key_name(ns)} || '' }}}}",
        ]
    else:
        lines += checkout(["persist-credentials: false"])
        lines += [
            "      - name: conform",
            f"        uses: {PIPELINES}/actions/conform@{ref}",
            "        with:",
            "          mode: check",
            f"          vault: {ns}",
        ]
    return lines


def detect_job(ref):
    lines = [
        "  detect:",
        "    name: detect",
        "    needs: conform",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    outputs:",
        "      changes: ${{ steps.detect.outputs.changes }}",
        "    steps:",
    ]
    lines += checkout(["fetch-depth: 0", "persist-credentials: false"])
    lines += ["      - name: detect", "        id: detect", f"        uses: {PIPELINES}/actions/detect@{ref}"]
    return lines


def changes(name, field):
    return f"fromJSON(needs.detect.outputs.changes).{name}.{field}"


def services_value(module):
    return ",".join(module["services"]) or "''"


def lane_job(project, module, side, ref, head):
    ns, name = project["ns"], module["name"]
    needs = f"{name}-{head}" if side == "code" else f"[ {name}-{head}, detect ]"
    lines = [
        f"  {name}-{side}:",
        f"    name: {name} / {side}",
        f"    needs: {needs}",
        f"    if: ${{{{ needs.{name}-{head}.outputs.{side} == 'true' }}}}",
        f"    uses: {PIPELINES}/.github/workflows/{side}.yml@{ref}",
        "    with:",
        f"      module: {name}",
        f"      vault: {ns}",
        f"      {side}_dir: {module[side]}",
    ]
    if side == "code":
        lines.append(f"      services: {services_value(module)}")
    if head == "reuse":
        checks = ("lint", "audit", "test") if side == "code" else ("validate", "plan")
        for check in checks:
            lines.append(f"      skip_{check}: ${{{{ needs.{name}-reuse.outputs.{check} }}}}")
    lines += ["    secrets:", f"      WARD_KEY: ${{{{ secrets.{key_name(ns)} }}}}"]
    return lines


def module_outputs(name):
    return [
        "    outputs:",
        f"      code: ${{{{ {changes(name, 'code')} }}}}",
        f"      infra: ${{{{ {changes(name, 'infra')} }}}}",
    ]


def changes_job(project, module, ref):
    name = module["name"]
    return [
        f"  {name}-changes:",
        f"    name: {name} / changes",
        "    needs: detect",
        f"    if: ${{{{ {changes(name, 'any')} }}}}",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        *module_outputs(name),
        "    steps:",
        "      - name: changes",
        "        env:",
        f"          CHANGES: ${{{{ toJSON({changes(name, 'any').rsplit('.any', 1)[0]}) }}}}",
        f"        run: echo \"{name} changes ${{CHANGES}}\" >> \"${{GITHUB_STEP_SUMMARY}}\"",
    ]


def reuse_job(project, module, ref):
    name = module["name"]
    return [
        f"  {name}-reuse:",
        f"    name: {name} / reuse",
        "    needs: detect",
        f"    if: ${{{{ {changes(name, 'any')} }}}}",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    outputs:",
        f"      code: ${{{{ {changes(name, 'code')} }}}}",
        f"      infra: ${{{{ {changes(name, 'infra')} }}}}",
        *[f"      {check}: ${{{{ steps.reuse.outputs.{check} }}}}" for check in CHECKS],
        "    steps:",
        "      - name: reuse",
        "        id: reuse",
        f"        uses: {PIPELINES}/actions/reuse@{ref}",
        "        with:",
        f"          module: {name}",
        f"          steps: {','.join(CHECKS)}",
        "          token: ${{ github.token }}",
    ]


def build_job(project, module, ref):
    ns, name = project["ns"], module["name"]
    return [
        f"  {name}-build:",
        f"    name: {name} / build",
        f"    needs: [ {name}-reuse, {name}-code, {name}-infra ]",
        f"    if: ${{{{ !failure() && !cancelled() && needs.{name}-reuse.result == 'success' }}}}",
        f"    runs-on: {RUNNER_BUILD}",
        "    timeout-minutes: 30",
        "    outputs:",
        "      tag: ${{ steps.tag.outputs.tag }}",
        "    steps:",
        *checkout(["fetch-depth: 0"]),
        "      - name: tag",
        "        id: tag",
        f"        uses: {PIPELINES}/actions/tag@{ref}",
        "        with:",
        f"          prefix: {name}",
        "      - name: build",
        f"        uses: {PIPELINES}/actions/step@{ref}",
        "        with:",
        f"          module: {name}",
        "          side: code",
        "          context: code",
        f"          dir: {module['code']}",
        "          step: build",
        "          environment: staging",
        f"          vault: {ns}",
        f"          key: ${{{{ secrets.{key_name(ns)} }}}}",
        f"          scopes: {ns}:secrets.{name}.infra.staging",
        "          tag: ${{ steps.tag.outputs.tag }}",
    ]


def release_job(project, module, ref):
    ns, name = project["ns"], module["name"]
    return [
        f"  {name}-release:",
        f"    name: {name} / release",
        f"    needs: {name}-build",
        f"    if: ${{{{ !failure() && !cancelled() && needs.{name}-build.result == 'success' }}}}",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    concurrency:",
        f"      group: release-{name}",
        "      cancel-in-progress: false",
        "    steps:",
        *checkout(["fetch-depth: 0", "persist-credentials: false"]),
        "      - name: secrets",
        "        uses: br4zz4/setup-ward@v1",
        "        with:",
        f"          vault: {ns}",
        f"          key: ${{{{ secrets.{key_name(ns)} }}}}",
        f"          scopes: {ns}:secrets.ci.common",
        "      - name: stamp",
        f"        uses: {PIPELINES}/actions/stamp@{ref}",
        "        with:",
        f"          tag: ${{{{ needs.{name}-build.outputs.tag }}}}",
        "          token: ${{ env.GH_PIPELINES_TOKEN }}",
    ]


def gate_job(project, ref):
    needs = ["conform", "detect"]
    for module in project["modules"]:
        needs += [f"{module['name']}-changes", f"{module['name']}-code", f"{module['name']}-infra"]
    return [
        "  gate:",
        "    name: check/pr",
        "    if: ${{ always() }}",
        f"    needs: [ {', '.join(needs)} ]",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    steps:",
        "      - name: gate",
        f"        uses: {PIPELINES}/actions/gate@{ref}",
        "        with:",
        "          results: ${{ toJSON(needs) }}",
    ]


def render_pr(project, ref):
    lines = [HEADER, "name: pr", "on:", "  pull_request:", "permissions:", "  contents: read", "  id-token: write"]
    lines += ["concurrency:", "  group: pr-${{ github.ref }}", "  cancel-in-progress: true", "jobs:"]
    lines += conform_job(project, "fix", ref) + detect_job(ref)
    for module in project["modules"]:
        lines += changes_job(project, module, ref)
        lines += lane_job(project, module, "code", ref, "changes")
        lines += lane_job(project, module, "infra", ref, "changes")
    lines += gate_job(project, ref)
    return lines


def render_main(project, ref):
    lines = [HEADER, "name: main", "on:", "  push:", "    branches: [ main ]", "permissions:"]
    lines += ["  contents: read", "  id-token: write", "  checks: read", "  pull-requests: read", "jobs:"]
    lines += conform_job(project, "check", ref) + detect_job(ref)
    for module in project["modules"]:
        lines += reuse_job(project, module, ref)
        lines += lane_job(project, module, "code", ref, "reuse")
        lines += lane_job(project, module, "infra", ref, "reuse")
        lines += build_job(project, module, ref)
        lines += release_job(project, module, ref)
    return lines


def releases_job(ref):
    lines = [
        "  release-start:",
        "    name: release / start",
        "    needs: conform",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    outputs:",
        "      releases: ${{ steps.releases.outputs.releases }}",
        "      environment: ${{ steps.releases.outputs.environment }}",
        "      module: ${{ steps.releases.outputs.module }}",
        "      services: ${{ steps.releases.outputs.services }}",
        "    steps:",
    ]
    lines += checkout(["fetch-depth: 0", "fetch-tags: true", "persist-credentials: false"])
    lines += ["      - name: releases", "        id: releases", f"        uses: {PIPELINES}/actions/releases@{ref}"]
    return lines


def deploy_job(project, ref):
    ns = project["ns"]
    rs = "needs.release-start.outputs"
    lines = [
        "  deploy:",
        "    name: deploy",
        "    needs: release-start",
        f"    if: ${{{{ needs.release-start.outputs.module != '' }}}}",
        "    concurrency:",
        f"      group: deploy-${{{{ {rs}.module }}}}-${{{{ {rs}.environment }}}}",
        "      cancel-in-progress: false",
        f"    uses: {PIPELINES}/.github/workflows/deploy.yml@{ref}",
        "    with:",
        f"      module: ${{{{ {rs}.module }}}}",
        f"      vault: {ns}",
        f"      tag: ${{{{ fromJSON({rs}.releases)[{rs}.module] }}}}",
        f"      environment: ${{{{ {rs}.environment }}}}",
        f"      services: ${{{{ {rs}.services }}}}",
        f"      code_dir: modules/${{{{ {rs}.module }}}}/code",
        f"      infra_dir: modules/${{{{ {rs}.module }}}}/infra",
        "    secrets:",
        f"      WARD_KEY: ${{{{ secrets.{key_name(ns)} }}}}",
    ]
    if project["restricted"]:
        lines.append(
            f"      WARD_KEY_RESTRICTED: ${{{{ github.event_name == 'workflow_dispatch' && secrets.{key_name(ns, True)} || '' }}}}"
        )
    return lines


def render_deploy(project, ref):
    lines = [HEADER, "name: deploy"]
    lines.append("run-name: ${{ github.event_name == 'push' && 'staging' || 'production' }} · ${{ github.ref_name }}")
    lines += ["on:", "  push:", f"    tags: [ {TAG_GLOB} ]", "  workflow_dispatch:"]
    lines += ["permissions:", "  contents: read", "  id-token: write", "  deployments: write", "jobs:"]
    lines += conform_job(project, "check", ref) + releases_job(ref)
    lines += deploy_job(project, ref)
    return lines


def render(project, ref=DEFAULT_REF):
    builders = {"pr.yml": render_pr, "main.yml": render_main, "deploy.yml": render_deploy}
    return {name: "\n".join(builders[name](project, ref)) + "\n" for name in FILES}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", required=True)
    parser.add_argument("--out")
    parser.add_argument("--ref", default=DEFAULT_REF, help="ref of br4zz4/pipelines the workflows call")
    args = parser.parse_args(argv)
    try:
        files = render(load_project(args.root), args.ref)
    except RenderError as error:
        print(f"render: {error}", file=sys.stderr)
        return 2
    out = args.out or os.path.join(args.root, ".github", "workflows")
    os.makedirs(out, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(out, name), "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
