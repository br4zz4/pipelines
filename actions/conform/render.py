#!/usr/bin/env python3
"""render — write a project's pr, main, build and deploy workflows from its registry.

Reads <root>/.github/modules.json and <root>/.ward/config.yaml, and writes
pr.yml, main.yml, build.yml and deploy.yml. The output is deterministic: modules are
sorted and nothing depends on the clock or the environment.

Usage: render.py --root <project> [--out <dir>] [--ref <ref>]
"""

import argparse
import json
import os
import re
import sys

HEADER = "# generated by br4zz4/pipelines render — do not edit"
RUNNER = "blacksmith-2vcpu-ubuntu-2404"
CODE_CHECKS = ("lint", "audit", "test")
INFRA_CHECKS = ("validate", "plan")
CHECKS = CODE_CHECKS + INFRA_CHECKS
PIPELINES = "br4zz4/pipelines"
DEFAULT_REF = "v2"
MODULE_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
SERVICES = ("postgres", "redis")
FILES = ("pr.yml", "main.yml", "build.yml", "deploy.yml")
PROMOTE_FILE = "promote.yml"
PRODUCTION_FAILURE = "github.event_name == 'workflow_run' && github.event.workflow_run.event == 'workflow_dispatch' && github.event.workflow_run.conclusion == 'failure' && startsWith(github.event.workflow_run.display_title, 'production')"
PRODUCTION_FAILURE_OR_DISPATCH = f"github.event_name == 'workflow_dispatch' || ({PRODUCTION_FAILURE})"
PROMOTE_KEYS = ("max_per_day",)
AUTOFIX_FILE = "autofix.yml"
INTAKE_FILE = "sentry-intake.yml"
AUTOFIX_KEYS = ("max_per_day", "sentry")
INTAKE_KEYS = ("schedule", "environments", "min_events")
INTAKE_SCHEDULE = "0 * * * *"
INTAKE_ENVIRONMENTS = ["production", "staging"]
INTAKE_MIN_EVENTS = 5
CRON = re.compile(r"^\S+( \S+){4}$")
SENTRY_KEYS = ("org", "project", "url")
SENTRY_DEFAULT_URL = "https://sentry.io"
SENTRY_SLUG = re.compile(r"^[a-z0-9][a-z0-9_-]*$")
SENTRY_URL = re.compile(r"^https://[^\s/]+(/[^\s]*[^\s/])?$")
RUN_NAME = (
    "run-name: ${{ inputs.rollback_to != '' && format('{0} · rollback · {1} (from {2})', inputs.environment || 'staging', inputs.rollback_to, github.ref_name)"
    " || format('{0} · {1}', github.event_name == 'push' && 'staging' || inputs.environment || 'staging', github.ref_name) }}"
)
TAG_GLOB = "'*.[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9].*'"


class RenderError(ValueError):
    pass


def read_json(path):
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except FileNotFoundError:
        raise RenderError(f"missing {path}")
    except json.JSONDecodeError as error:
        raise RenderError(f"{path}: invalid JSON ({error})")


def ward_vaults(path):
    try:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    except FileNotFoundError:
        raise RenderError(f"missing {path}")
    names, in_vaults = [], False
    for line in text.splitlines():
        if re.match(r"^vaults:\s*$", line):
            in_vaults = True
            continue
        if in_vaults and line.strip() and not line[0].isspace() and not line.startswith("-"):
            in_vaults = False
        if not in_vaults:
            continue
        match = re.match(r"^\s*-?\s*name:\s*['\"]?([^'\"\s#]+)", line)
        if match:
            names.append(match.group(1))
    return names


def namespace(vaults):
    """Return (namespace, has_restricted). The project namespace is the default
    vault that has a `::restricted` pair; without any pair, the only default."""
    defaults = {}
    for name in vaults:
        if name.endswith("::restricted"):
            continue
        base = name[: -len("::default")] if name.endswith("::default") else name
        if "::" in base:
            continue
        if base in defaults:
            raise RenderError(f".ward/config.yaml declares vault '{base}' twice (default and ::default)")
        defaults[base] = name
    paired = sorted(ns for ns in defaults if f"{ns}::restricted" in vaults)
    if len(paired) > 1:
        raise RenderError(f".ward/config.yaml declares more than one project namespace: {', '.join(paired)}")
    if paired:
        return paired[0], True
    if len(defaults) == 1:
        return next(iter(defaults)), False
    if not defaults:
        raise RenderError(".ward/config.yaml must declare a default vault <ns> (or <ns>::default)")
    raise RenderError(
        ".ward/config.yaml declares several default vaults without a ::restricted pair to pick the project: "
        + ", ".join(sorted(defaults))
    )


def key_name(ns, restricted=False):
    base = "WARD_KEY_" + re.sub(r"[^A-Za-z0-9]", "_", ns).upper()
    return base + "_RESTRICTED" if restricted else base


def promote_config(registry):
    if "promote" not in registry:
        return None
    config = registry["promote"]
    if not isinstance(config, dict):
        raise RenderError("promote must be an object")
    for key in config:
        if key not in PROMOTE_KEYS:
            raise RenderError(f"promote: unknown key '{key}' (allowed: {', '.join(PROMOTE_KEYS)})")
    limit = config.get("max_per_day", 0)
    if isinstance(limit, bool) or not isinstance(limit, int) or ("max_per_day" in config and limit < 1):
        raise RenderError("promote.max_per_day must be an integer >= 1")
    return {"max_per_day": limit}


def sentry_config(registry):
    if "sentry" not in registry:
        return None
    config = registry["sentry"]
    if not isinstance(config, dict):
        raise RenderError("sentry must be an object")
    for key in config:
        if key not in SENTRY_KEYS:
            raise RenderError(f"sentry: unknown key '{key}' (allowed: {', '.join(SENTRY_KEYS)})")
    for key in ("org", "project"):
        value = config.get(key)
        if not isinstance(value, str) or not SENTRY_SLUG.match(value):
            raise RenderError(f"sentry.{key} must be a non-empty slug matching [a-z0-9][a-z0-9_-]*")
    url = config.get("url", SENTRY_DEFAULT_URL)
    if not isinstance(url, str) or not SENTRY_URL.match(url):
        raise RenderError("sentry.url must be an https:// URL without a trailing slash")
    return {"org": config["org"], "project": config["project"], "url": url}


def autofix_config(registry, sentry):
    if "autofix" not in registry:
        return None
    config = registry["autofix"]
    if not isinstance(config, dict):
        raise RenderError("autofix must be an object")
    for key in config:
        if key not in AUTOFIX_KEYS:
            raise RenderError(f"autofix: unknown key '{key}' (allowed: {', '.join(AUTOFIX_KEYS)})")
    limit = config.get("max_per_day", 0)
    if isinstance(limit, bool) or not isinstance(limit, int) or limit < 0:
        raise RenderError("autofix.max_per_day must be an integer >= 0")
    return {"max_per_day": limit, "sentry": intake_config(config, sentry)}


def intake_config(config, sentry):
    if "sentry" not in config:
        return None
    intake = config["sentry"]
    if not isinstance(intake, dict):
        raise RenderError("autofix.sentry must be an object")
    for key in intake:
        if key not in INTAKE_KEYS:
            raise RenderError(f"autofix.sentry: unknown key '{key}' (allowed: {', '.join(INTAKE_KEYS)})")
    schedule = intake.get("schedule", INTAKE_SCHEDULE)
    if not isinstance(schedule, str) or not CRON.match(schedule) or "'" in schedule:
        raise RenderError("autofix.sentry.schedule must be a cron expression with 5 fields")
    environments = intake.get("environments", INTAKE_ENVIRONMENTS)
    if (
        not isinstance(environments, list)
        or not environments
        or not all(isinstance(e, str) and re.match(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$", e) for e in environments)
    ):
        raise RenderError("autofix.sentry.environments must be a non-empty list of environment names")
    min_events = intake.get("min_events", INTAKE_MIN_EVENTS)
    if isinstance(min_events, bool) or not isinstance(min_events, int) or min_events < 1:
        raise RenderError("autofix.sentry.min_events must be an integer >= 1")
    if sentry is None:
        raise RenderError("autofix.sentry requires the top-level sentry key")
    return {"schedule": schedule, "environments": list(environments), "min_events": min_events}


def sentry_inputs(project):
    sentry = project["sentry"]
    if sentry is None:
        return []
    return [
        f"      sentry_org: {sentry['org']}",
        f"      sentry_project: {sentry['project']}",
        f"      sentry_url: {sentry['url']}",
    ]


def load_project(root):
    registry = read_json(os.path.join(root, ".github", "modules.json"))
    ns, restricted = namespace(ward_vaults(os.path.join(root, ".ward", "config.yaml")))
    sentry = sentry_config(registry)
    modules = registry.get("modules") or {}
    if not modules:
        raise RenderError(".github/modules.json declares no modules")
    result = []
    for name in sorted(modules):
        if not MODULE_NAME.match(name):
            raise RenderError(f"module '{name}' must match [a-z][a-z0-9_]*")
        spec = modules[name] or {}
        services = list(spec.get("services") or [])
        for service in services:
            if service not in SERVICES:
                raise RenderError(f"module '{name}': service '{service}' is not in the catalog ({', '.join(SERVICES)})")
        code = (spec.get("code") or {}).get("dir") or f"modules/{name}/code"
        infra = (spec.get("infra") or {}).get("dir") or f"modules/{name}/infra"
        result.append({"name": name, "services": services, "code": code, "infra": infra})
    return {
        "ns": ns,
        "restricted": restricted,
        "modules": result,
        "extra": list(registry.get("extra_workflows") or []),
        "shared": list(registry.get("shared") or []),
        "promote": promote_config(registry),
        "sentry": sentry,
        "autofix": autofix_config(registry, sentry),
    }


def checkout(extra=None):
    lines = ["      - name: checkout", "        uses: actions/checkout@v7"]
    if extra:
        lines.append("        with:")
        lines.extend(f"          {line}" for line in extra)
    return lines


def conform_job(project, mode, ref, condition=None):
    ns = project["ns"]
    lines = ["  conform:", "    name: conform"]
    if condition:
        lines.append(f"    if: ${{{{ {condition} }}}}")
    lines += [f"    runs-on: {RUNNER}", "    timeout-minutes: 5", "    steps:"]
    if mode == "fix":
        lines += checkout(
            [
                "ref: ${{ github.head_ref }}",
                "repository: ${{ github.event.pull_request.head.repo.full_name }}",
                "persist-credentials: false",
            ]
        )
        lines += [
            "      - name: conform",
            f"        uses: {PIPELINES}/actions/conform@{ref}",
            "        with:",
            "          mode: fix",
            f"          vault: {ns}",
            f"          key: ${{{{ github.event.pull_request.head.repo.full_name == github.repository && secrets.{key_name(ns)} || '' }}}}",
        ]
    else:
        lines += checkout(["persist-credentials: false"])
        lines += [
            "      - name: conform",
            f"        uses: {PIPELINES}/actions/conform@{ref}",
            "        with:",
            "          mode: check",
            f"          vault: {ns}",
        ]
    return lines


def detect_job(ref):
    lines = [
        "  detect:",
        "    name: detect",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    outputs:",
        "      changes: ${{ steps.detect.outputs.changes }}",
        "    steps:",
    ]
    lines += checkout(["fetch-depth: 0", "fetch-tags: true", "persist-credentials: false"])
    lines += ["      - name: detect", "        id: detect", f"        uses: {PIPELINES}/actions/detect@{ref}"]
    return lines


def changes(name, field):
    return f"fromJSON(needs.detect.outputs.changes).{name}.{field}"


def services_value(module):
    return ",".join(module["services"]) or "''"


def lane_job(project, module, side, ref):
    ns, name = project["ns"], module["name"]
    needs = f"{name}-changes" if side == "code" else f"[ {name}-changes, detect ]"
    lines = [
        f"  {name}-{side}:",
        f"    name: {name} / {side}",
        f"    needs: {needs}",
        f"    if: ${{{{ needs.{name}-changes.outputs.{side} == 'true' }}}}",
        f"    uses: {PIPELINES}/.github/workflows/{side}.yml@{ref}",
        "    with:",
        f"      module: {name}",
        f"      vault: {ns}",
        f"      {side}_dir: {module[side]}",
    ]
    if side == "code":
        lines.append(f"      services: {services_value(module)}")
    lines += ["    secrets:", f"      WARD_KEY: ${{{{ secrets.{key_name(ns)} }}}}"]
    return lines


def changes_job(project, module, ref):
    name = module["name"]
    return [
        f"  {name}-changes:",
        f"    name: {name} / changes",
        "    needs: [ conform, detect ]",
        f"    if: ${{{{ {changes(name, 'any')} }}}}",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    outputs:",
        f"      code: ${{{{ {changes(name, 'code')} }}}}",
        f"      infra: ${{{{ {changes(name, 'infra')} }}}}",
        "    steps:",
        "      - name: changes",
        "        env:",
        f"          CHANGES: ${{{{ toJSON({changes(name, 'any').rsplit('.any', 1)[0]}) }}}}",
        f"        run: echo \"{name} changes ${{CHANGES}}\" >> \"${{GITHUB_STEP_SUMMARY}}\"",
    ]


def gate_job(project, ref):
    needs = ["conform", "detect"]
    for module in project["modules"]:
        needs += [f"{module['name']}-changes", f"{module['name']}-code", f"{module['name']}-infra"]
    return [
        "  gate:",
        "    name: check/pr",
        "    if: ${{ always() }}",
        f"    needs: [ {', '.join(needs)} ]",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    steps:",
        "      - name: gate",
        f"        uses: {PIPELINES}/actions/gate@{ref}",
        "        with:",
        "          results: ${{ toJSON(needs) }}",
    ]


def render_pr(project, ref):
    lines = [HEADER, "name: pr", "on:", "  pull_request:", "permissions:", "  contents: read", "  id-token: write"]
    lines += ["concurrency:", "  group: pr-${{ github.ref }}", "  cancel-in-progress: true", "jobs:"]
    lines += conform_job(project, "fix", ref) + detect_job(ref)
    for module in project["modules"]:
        lines += changes_job(project, module, ref)
        lines += lane_job(project, module, "code", ref)
        lines += lane_job(project, module, "infra", ref)
    lines += gate_job(project, ref)
    return lines


def split_job(project, ref):
    ns = project["ns"]
    lines = [
        "  split:",
        "    name: build / split",
        "    needs: [ conform, detect ]",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 10",
        "    steps:",
    ]
    lines += checkout(["fetch-depth: 0", "fetch-tags: true", "persist-credentials: false"])
    lines += [
        "      - name: secrets",
        "        uses: br4zz4/setup-ward@v1",
        "        with:",
        f"          vault: {ns}",
        f"          key: ${{{{ secrets.{key_name(ns)} }}}}",
        f"          scopes: {ns}:secrets.ci.common",
        "      - name: split",
        f"        uses: {PIPELINES}/actions/split@{ref}",
        "        with:",
        "          changes: ${{ needs.detect.outputs.changes }}",
        "          token: ${{ env.GH_PIPELINES_TOKEN }}",
    ]
    return lines


def render_main(project, ref):
    lines = [HEADER, "name: main", "on:", "  push:", "    branches: [ main ]", "permissions:"]
    lines += ["  contents: read", "  id-token: write", "jobs:"]
    lines += conform_job(project, "check", ref) + detect_job(ref) + split_job(project, ref)
    return lines


def target_job(ref):
    lines = [
        "  target:",
        "    name: target",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    outputs:",
    ]
    lines += [f"      {key}: ${{{{ steps.target.outputs.{key} }}}}" for key in ("module", "tag", "code_dir", "infra_dir", "services", "code", "infra", "reuse")]
    lines += ["    steps:"]
    lines += checkout(["fetch-depth: 0", "fetch-tags: true", "persist-credentials: false"])
    lines += ["      - name: target", "        id: target", f"        uses: {PIPELINES}/actions/target@{ref}"]
    return lines


def build_job(project, ref):
    ns = project["ns"]
    t = "needs.target.outputs"
    lines = [
        "  build:",
        "    name: build",
        "    needs: [ conform, target ]",
        "    concurrency:",
        f"      group: build-${{{{ {t}.module }}}}",
        "      cancel-in-progress: true",
        f"    uses: {PIPELINES}/.github/workflows/build.yml@{ref}",
        "    with:",
        f"      module: ${{{{ {t}.module }}}}",
        f"      vault: {ns}",
        f"      tag: ${{{{ {t}.tag }}}}",
        f"      code_dir: ${{{{ {t}.code_dir }}}}",
        f"      infra_dir: ${{{{ {t}.infra_dir }}}}",
        f"      services: ${{{{ {t}.services }}}}",
        f"      code: ${{{{ {t}.code }}}}",
        f"      infra: ${{{{ {t}.infra }}}}",
        f"      reuse: ${{{{ {t}.reuse }}}}",
    ]
    lines += sentry_inputs(project)
    lines += [
        "    secrets:",
        f"      WARD_KEY: ${{{{ secrets.{key_name(ns)} }}}}",
    ]
    return lines


def render_build(project, ref):
    lines = [HEADER, "name: build", "run-name: ${{ github.ref_name }}", "on:", "  push:", "    tags: [ 'build/**' ]"]
    lines += ["permissions:", "  contents: read", "  id-token: write", "  checks: read", "  pull-requests: read", "jobs:"]
    lines += conform_job(project, "check", ref) + target_job(ref) + build_job(project, ref)
    return lines


def releases_job(ref):
    lines = [
        "  release-start:",
        "    name: release / start",
        f"    runs-on: {RUNNER}",
        "    timeout-minutes: 5",
        "    outputs:",
        "      releases: ${{ steps.releases.outputs.releases }}",
        "      environment: ${{ steps.releases.outputs.environment }}",
        "      module: ${{ steps.releases.outputs.module }}",
        "      services: ${{ steps.releases.outputs.services }}",
        "      tag: ${{ steps.releases.outputs.tag }}",
        "      code_dir: ${{ steps.releases.outputs.code_dir }}",
        "      infra_dir: ${{ steps.releases.outputs.infra_dir }}",
        "      rollback_of: ${{ steps.releases.outputs.rollback_of }}",
        "    steps:",
    ]
    lines += checkout(["fetch-depth: 0", "fetch-tags: true", "persist-credentials: false"])
    lines += [
        "      - name: releases",
        "        id: releases",
        f"        uses: {PIPELINES}/actions/releases@{ref}",
        "        with:",
        "          environment: ${{ inputs.environment }}",
        "          rollback_to: ${{ inputs.rollback_to }}",
    ]
    return lines


def deploy_job(project, ref):
    ns = project["ns"]
    rs = "needs.release-start.outputs"
    lines = [
        "  deploy:",
        "    name: deploy",
        "    needs: [ conform, release-start ]",
        f"    if: ${{{{ needs.release-start.outputs.module != '' }}}}",
        "    concurrency:",
        f"      group: deploy-${{{{ {rs}.module }}}}-${{{{ {rs}.environment }}}}",
        "      cancel-in-progress: false",
        f"    uses: {PIPELINES}/.github/workflows/deploy.yml@{ref}",
        "    with:",
        f"      module: ${{{{ {rs}.module }}}}",
        f"      vault: {ns}",
        f"      tag: ${{{{ fromJSON({rs}.releases)[{rs}.module] }}}}",
        f"      environment: ${{{{ {rs}.environment }}}}",
        f"      code_dir: ${{{{ {rs}.code_dir }}}}",
        f"      infra_dir: ${{{{ {rs}.infra_dir }}}}",
        f"      rollback_of: ${{{{ {rs}.rollback_of }}}}",
    ]
    if project["promote"] is not None:
        lines += ["      require_promoted: ${{ !inputs.force }}", "      promote_enabled: true"]
    lines += sentry_inputs(project)
    lines += [
        "    secrets:",
        f"      WARD_KEY: ${{{{ secrets.{key_name(ns)} }}}}",
    ]
    return lines


def render_deploy(project, ref):
    lines = [HEADER, "name: deploy"]
    lines.append(RUN_NAME)
    lines += [
        "on:",
        "  push:",
        f"    tags: [ {TAG_GLOB} ]",
        "  workflow_dispatch:",
        "    inputs:",
        "      environment:",
        "        description: staging | production",
        "        required: false",
        "        default: staging",
        "        type: choice",
        "        options: [ staging, production ]",
        "      rollback_to:",
        "        description: Release to roll back to; set by a failed deploy",
        "        required: false",
        "        default: ''",
        "        type: string",
    ]
    if project["promote"] is not None:
        lines += [
            "      force:",
            "        description: Deploy to production without the promote record",
            "        required: false",
            "        default: false",
            "        type: boolean",
        ]
    lines += ["permissions:", "  contents: read", "  id-token: write", "  deployments: write", "  actions: write", "jobs:"]
    lines += conform_job(project, "check", ref) + releases_job(ref)
    lines += deploy_job(project, ref)
    return lines


def modules_json(project):
    modules = {m["name"]: {"code": m["code"], "services": ",".join(m["services"])} for m in project["modules"]}
    return json.dumps(modules, sort_keys=True, separators=(",", ":"))


